# -*- coding: utf-8 -*-
"""
Python 函数 - Lambda 匿名函数
=====================================

什么是 lambda 函数？
--------------------
lambda 是一种创建匿名函数的方式，即没有函数名的函数。
语法：lambda 参数: 表达式


基本语法
--------
# 普通函数
def 函数名(参数):
    return 表达式

# lambda 函数
lambda 参数: 表达式


示例 1：基础对比
-----------------
"""
# 普通函数
def add(a, b):
    return a + b

# lambda 函数（实现相同功能）
add_lambda = lambda a, b: a + b

print(add(3, 5))          # 输出: 8
print(add_lambda(3, 5))   # 输出: 8


"""
示例 2：lambda 的特点
---------------------
1. 匿名：通常不需要函数名
2. 单行：只能包含一个表达式
3. 立即返回：表达式结果自动返回
4. 常用于：作为参数传递给其他函数
"""

# 常用于排序
students = [
    {'name': '小明', 'age': 18},
    {'name': '小红', 'age': 16},
    {'name': '小刚', 'age': 20}
]

# 使用 lambda 按年龄排序
students.sort(key=lambda s: s['age'])
print(students)
# 输出: [{'name': '小红', 'age': 16}, {'name': '小明', 'age': 18}, {'name': '小刚', 'age': 20}]


