# 1. 第一步：先只问年龄（不要问其他的！）
age = int(input('请输入你的年龄：'))

# 2. 立刻判断年龄
# 如果年龄不符合，进入 else，直接结束
if 18 <= age <= 45:
    print('你的年龄符合参赛要求')
    
    # =========== 核心变化在这里 ===========
    # 只有当程序“走进”了这个 if 里面（也就是年龄符合了）
    # 我们才开始问这一堆后续问题
    # 这就是你想要的“符合才继续往下执行”
    # ====================================
    
    has_report = input('是否提交体检报告？(是/否) ')
    level = int(input('请输入你的会员等级[1/2/3]：'))

    # 后面的逻辑保持不变，全都缩进在这个 if 里面
    if has_report == '是':
        print('你的体检报告已提交')
        if level == 1:
            print('你获得纪念T恤')
        elif level == 2:
            print('你获得跑鞋一双')
        elif level == 3:
            print('你获得运动耳机一副')
        else:
            print('无效的会员等级')
    elif has_report == '否':
        print('你还没有提交体检报告')
    else:
        print('请输入“是”或“否”回答体检报告问题')

else:
    # 3. 如果年龄不符合，程序直接跳到这里
    # 因为上面那些 input 代码都在 if 里，这里根本不会执行
    print('你的参赛年龄不符合参赛要求')
    # 程序运行到这里，后面没有代码了，自然就“直接结束”了